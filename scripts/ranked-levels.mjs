import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

export const RANKED_LEVELS = ["B1", "B2", "C1"];
// Conservative gameplay subset: avoid abbreviations and a few sensitive terms.
// The full educational catalogue remains unchanged and available separately.
export const RANKED_EXCLUDED_WORDS = new Set([
  "aborigine",
  "gypsy",
  "hiv",
  "lust",
  "ness",
  "pee",
  "prick",
  "queer",
  "rape",
  "raunchy",
  "retard",
  "sex",
  "sexual",
  "sexy",
  "suicide",
]);

export function selectRankedWords(catalogue) {
  return RANKED_LEVELS.flatMap((level) => {
    const words = [
      ...new Set(
        catalogue
          .filter(
            ([word, , band, definition, source]) =>
              band === level &&
              definition &&
              ["cefrj", "octanove"].includes(source) &&
              /^[a-z]{3,18}$/.test(word) &&
              !RANKED_EXCLUDED_WORDS.has(word),
          )
          .map(([word]) => word),
      ),
    ].sort();
    if (words.length < 300)
      throw new Error(`Insufficient ranked words for ${level}`);
    return words.map((word) => [level, word]);
  });
}

function section(source, name) {
  const start = `-- BEGIN ${name}`;
  const end = `-- END ${name}`;
  const content = source.split(start)[1]?.split(end)[0];
  if (!content) throw new Error(`Missing schema section: ${name}`);
  return content.trim();
}

function rpc(source, name) {
  const content = source.match(
    new RegExp(
      `create or replace function public\\.${name}\\([\\s\\S]*?end; \\$\\$;`,
    ),
  )?.[0];
  if (!content) throw new Error(`Missing schema RPC: ${name}`);
  return content;
}

export function generateRankedMigration(
  root = path.resolve(fileURLToPath(new URL("..", import.meta.url))),
) {
  const catalogue = JSON.parse(
    readFileSync(path.join(root, "src/data/cefr-words.json"), "utf8"),
  );
  const words = selectRankedWords(catalogue);
  const counts = Object.fromEntries(
    RANKED_LEVELS.map((level) => [
      level,
      words.filter(([band]) => band === level).length,
    ]),
  );
  const attribution = `-- Generated by node scripts/ranked-levels.mjs; do not edit generated word rows.
-- CEFR-J Wordlist v1.5: Yukio Tono, Tokyo University of Foreign Studies;
-- copyright Tono Laboratory, TUFS. https://github.com/openlanguageprofiles/olp-en-cefrj
-- Octanove Vocabulary Profile C1/C2 v1.0: Octanove Labs (C1 subset).
-- Adapted data arrangement: CC BY-SA 4.0. https://creativecommons.org/licenses/by-sa/4.0/
-- Single alphabetic headwords 3-18 letters; conservative gameplay exclusions.
-- Full source notices: public/licenses/CEFR-J-NOTICE.md; public/licenses/CC-BY-SA-4.0.txt.
-- No source endorsement. See docs/vocabulary.md for import provenance/limitations.
-- B1 ${counts.B1}; B2 ${counts.B2}; C1 ${counts.C1}. Existing A1/A2 banks are unchanged.`;
  const seed = `${attribution}\ninsert into public.words(level,word) values\n${words.map(([level, word]) => `('${level}','${word}')`).join(",\n")}\non conflict(level,word) do nothing;`;
  const schemaPath = path.join(root, "supabase/schema.sql");
  let schema = readFileSync(schemaPath, "utf8");
  schema = schema.replace(
    /-- BEGIN ADVANCED WORD BANK[\s\S]*?-- END ADVANCED WORD BANK/,
    `-- BEGIN ADVANCED WORD BANK\n${seed}\n-- END ADVANCED WORD BANK`,
  );
  writeFileSync(schemaPath, schema);
  const migration = `-- 10Qadam ranked levels upgrade: run the entire transaction once in Supabase SQL editor.
-- Safe to reapply. No existing ratings, words, rooms, players or answers are reset.
-- Requires the existing supabase/schema.sql tables/RPCs, not an empty project.
begin;
${section(schema, "RANKED LEVEL UPGRADE")}

${rpc(schema, "join_matchmaking")}

${rpc(schema, "finish_match")}

-- CREATE OR REPLACE retains existing RPC privileges; assert the same authenticated-only boundary.
revoke all on function public.join_matchmaking(text,text),public.finish_match(uuid) from public, anon;
grant execute on function public.join_matchmaking(text,text),public.finish_match(uuid) to authenticated;

${seed}
commit;
`;
  mkdirSync(path.join(root, "supabase/migrations"), { recursive: true });
  writeFileSync(
    path.join(root, "supabase/migrations/20261014_ranked_levels.sql"),
    migration,
  );
  return { counts, total: words.length };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  console.log(JSON.stringify(generateRankedMigration()));
}
